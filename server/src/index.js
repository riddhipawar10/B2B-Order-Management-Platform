import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import dotenv from 'dotenv';
import { query } from './config/db.js';
import authRoutes from './routes/auth.js';
import productRoutes from './routes/products.js';
import orderRoutes from './routes/orders.js';
import invoiceRoutes from './routes/invoices.js';
import activityRoutes from './routes/activity.js';
import { notFound,errorHandler } from './middleware/errors.js';
dotenv.config();
if(!process.env.JWT_SECRET || process.env.JWT_SECRET.includes('replace_this')) console.warn('WARNING: Set a private JWT_SECRET in server/.env before using this beyond local demo.');
const app=express();
app.use(helmet());app.use(cors({origin:process.env.CLIENT_ORIGIN||'http://localhost:5173'}));app.use(express.json({limit:'1mb'}));
app.get('/api/health',async(req,res)=>{try{await query('SELECT 1');res.json({status:'ok',database:'connected',service:'Arrowstack B2B API'});}catch(e){res.status(503).json({status:'error',database:'disconnected'});}});
app.use('/api/auth',authRoutes);app.use('/api/products',productRoutes);app.use('/api/orders',orderRoutes);app.use('/api/invoices',invoiceRoutes);app.use('/api/activity',activityRoutes);
app.use(notFound);app.use(errorHandler);
const port=process.env.PORT||5000;app.listen(port,()=>console.log(`Arrowstack API running at http://localhost:${port}`));
